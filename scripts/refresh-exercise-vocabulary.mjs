#!/usr/bin/env node
/**
 * REFRESH THE REAL-VOCABULARY SNAPSHOT — read-only.
 *
 *   node scripts/refresh-exercise-vocabulary.mjs
 *
 * Pulls the DISTINCT strength exercise names out of `planned_workouts` and `workouts` and writes
 * them to `src/lib/__fixtures__/real-exercise-vocabulary.json`, which
 * `exercise-config.vocabulary-guard.test.ts` reads.
 *
 * ⛔ WHY A SNAPSHOT AND NOT A LIVE QUERY IN THE TEST. The guard has to run for anyone, offline, with
 * no credentials and no network — `deno test --no-check` and nothing else. A test that reaches for
 * prod is a test that fails on a plane and gets deleted. The snapshot makes the corpus a committed,
 * reviewable artifact; this script is the only thing that touches the database, it is READ-ONLY, and
 * it is run deliberately.
 *
 * ⚠️ NAMES ONLY. No user ids, no dates, no set data, no weights — nothing but the exercise strings
 * the app has to be able to resolve. The file is a vocabulary, not athlete data.
 *
 * Requires SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY (reads `.env`). Pass user ids as arguments, or
 * it defaults to every user — the vocabulary is the union either way.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

// Minimal .env reader — the shell chokes on some values in this file, so parse rather than source.
function env(name) {
  if (process.env[name]) return process.env[name];
  const p = path.join(root, '.env');
  if (!existsSync(p)) return null;
  for (const line of readFileSync(p, 'utf8').split('\n')) {
    const m = line.match(/^\s*([A-Z_][A-Z0-9_]*)\s*=\s*(.*)$/);
    if (m && m[1] === name) return m[2].trim().replace(/^["']|["']$/g, '');
  }
  return null;
}

const URL_BASE = (env('SUPABASE_URL') || '').replace(/\/+$/, '');
const KEY = env('SUPABASE_SERVICE_ROLE_KEY');
if (!URL_BASE || !KEY) {
  console.error('Missing SUPABASE_URL / SUPABASE_SERVICE_ROLE_KEY (checked env and .env).');
  process.exit(1);
}
const userIds = process.argv.slice(2);

async function page(table, extra) {
  const out = [];
  for (let offset = 0; ; offset += 1000) {
    const qs = new URLSearchParams({ select: 'strength_exercises', limit: '1000', offset: String(offset), ...extra });
    const res = await fetch(`${URL_BASE}/rest/v1/${table}?${qs}`, {
      headers: { apikey: KEY, Authorization: `Bearer ${KEY}` },
    });
    if (!res.ok) throw new Error(`${table} ${res.status} ${await res.text()}`);
    const rows = await res.json();
    out.push(...rows);
    if (rows.length < 1000) break;
  }
  return out;
}

const names = new Map(); // name → Set<source>
const add = (n, src) => {
  const s = String(n ?? '').trim();
  if (!s) return;
  if (!names.has(s)) names.set(s, new Set());
  names.get(s).add(src);
};

for (const [table, src, extra] of [
  ['planned_workouts', 'planned', { type: 'eq.strength' }],
  ['workouts', 'logged', {}],
]) {
  const filters = userIds.length === 1 ? { ...extra, user_id: `eq.${userIds[0]}` } : extra;
  const rows = await page(table, filters);
  for (const r of rows) {
    const ex = r.strength_exercises;
    if (Array.isArray(ex)) for (const e of ex) add(e?.name, src);
  }
}

const sorted = [...names.keys()].sort((a, b) => a.localeCompare(b));
const payload = {
  _comment:
    'GENERATED by scripts/refresh-exercise-vocabulary.mjs — read-only snapshot of the exercise ' +
    'names actually present in planned_workouts + workouts. Names only, no athlete data. ' +
    'Read by src/lib/exercise-config.vocabulary-guard.test.ts. Re-run the script to refresh.',
  count: sorted.length,
  names: sorted.map((n) => ({ name: n, sources: [...names.get(n)].sort() })),
};

const outDir = path.join(root, 'src/lib/__fixtures__');
mkdirSync(outDir, { recursive: true });
const outPath = path.join(outDir, 'real-exercise-vocabulary.json');
writeFileSync(outPath, JSON.stringify(payload, null, 2) + '\n');
console.log(`wrote ${sorted.length} distinct exercise names → ${path.relative(root, outPath)}`);
